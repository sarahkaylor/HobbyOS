#!/bin/sh
# gen-icewm-menu.sh DISK DESKTOP_C OUT_DIR [MDIR]
#
# Generates IceWM's start menu (/ICEWM/menu) and toolbar (/ICEWM/toolbar)
# for a DESKTOP=icewm disk so they mirror the default HobbyOS desktop's
# Apps menu (icewm.md §9):
#
#   Apps          the desktop's pinned_apps[], in order (read out of
#                 src/user/desktop.c itself -- the single source of truth,
#                 so the two menus cannot drift)
#   Games         pinned_games[] (in order) + every .BIN/ELF in /GAMES
#   All programs  every other root .BIN on THIS disk (sorted, in submenus of
#                 at most 24), i.e. what the desktop's menu lists
#   XEyes / XCalc the real-Xlib clients, as before
#
# Native entries run through the host:  HBHOST.BIN <NAME.BIN>.  Only files
# that are really on the disk are listed.  Writes OUT_DIR/menu and
# OUT_DIR/toolbar.
set -eu
DISK=$1
DESK=$2
OUT=$3
MDIR=${4:-mdir}

[ -f "$DESK" ] || { echo "[icewm-menu] ERROR: $DESK missing"; exit 1; }
mkdir -p "$OUT"

pinned() { # pinned_apps | pinned_games -> one NAME.BIN per line, in order
  awk -v arr="$1" '
    index($0, "const pinned_" arr "[]") || index($0, arr "[] = {") { on = 1 }
    on { print }
    on && /};/ { exit }' "$DESK" | grep -o '"[^"]*"' | tr -d '"'
}
APPS=$(pinned apps)
GAMES=$(pinned games)
[ -n "$APPS" ] || { echo "[icewm-menu] ERROR: no pinned_apps in $DESK"; exit 1; }

# Root and /GAMES listings (upper-case 8.3 names, as the kernel reports them).
ROOT=$("$MDIR" -b -i "$DISK" ::/ 2>/dev/null | sed -n 's|^::/||p' | tr 'a-z' 'A-Z' | sort -u)
GDIR=$("$MDIR" -b -i "$DISK" ::/GAMES 2>/dev/null | sed -n 's|^::/GAMES/||p' | tr 'a-z' 'A-Z' | sort -u || true)
on_disk() { printf '%s\n' "$ROOT" | grep -qx "$1"; }
# IceWM takes the first '_' of a label as the hotkey marker and drops it
# (APPS_T showed as "APPST"); a leading '_' absorbs that so names keep theirs.
label() { case "${1%.BIN}" in *_*) printf '_%s' "${1%.BIN}" ;; *) printf '%s' "${1%.BIN}" ;; esac; }

# X-stack / session binaries are not desktop apps (and XEYESR/XCALCR keep
# their own real-X entries below).
SKIP="XSESSION.BIN XHOBBY.BIN ICEWM.BIN ICEWMBG.BIN ICEWMHNT.BIN ICESH.BIN HBHOST.BIN XFILES.BIN XEYESR.BIN XCALCR.BIN"
skipped() { for s in $SKIP; do [ "$1" = "$s" ] && return 0; done; return 1; }
in_list() { printf '%s\n' "$2" | grep -qx "$1"; }

M="$OUT/menu"
{
  echo "# /ICEWM/menu -- GENERATED at disk-build time by src/user/x11sess/gen-icewm-menu.sh"
  echo "# from src/user/desktop.c (pinned_apps/pinned_games) and this disk's files."
  echo "# Native HobbyOS programs run in an X window through HBHOST.BIN (icewm.md §9)."
  on_disk XFILES.BIN && echo 'prog "Files (X11)" folder /XFILES.BIN'
  echo 'separator'
  echo 'menu "Apps" folder {'
  for a in $APPS; do
    on_disk "$a" && echo "    prog \"$(label "$a")\" app HBHOST.BIN $a"
  done
  echo '}'
  echo 'menu "Games" folder {'
  for g in $GAMES; do
    on_disk "$g" && echo "    prog \"$(label "$g")\" app HBHOST.BIN $g"
  done
  for g in $GDIR; do
    case "$g" in .|..) continue;; esac
    in_list "$g" "$GAMES" && on_disk "$g" && continue
    echo "    prog \"$(label "$g")\" app HBHOST.BIN /GAMES/$g"
  done
  echo '}'
  echo 'menu "All programs" folder {'
  rest=""
  for f in $ROOT; do
    case "$f" in *.BIN) ;; *) continue;; esac
    in_list "$f" "$APPS" && continue
    in_list "$f" "$GAMES" && continue
    skipped "$f" && continue
    rest="$rest $f"
  done
  # submenus of at most 24 entries, named by their first..last program
  set -- $rest
  while [ $# -gt 0 ]; do
    chunk=""; n=0
    while [ $# -gt 0 ] && [ $n -lt 24 ]; do chunk="$chunk $1"; shift; n=$((n + 1)); done
    first=$(echo $chunk | awk '{print $1}'); last=$(echo $chunk | awk '{print $NF}')
    echo "    menu \"_${first%.BIN} - ${last%.BIN}\" folder {"
    for f in $chunk; do echo "        prog \"$(label "$f")\" app HBHOST.BIN $f"; done
    echo '    }'
  done
  echo '}'
  echo 'separator'
  on_disk XEYESR.BIN && echo 'prog "XEyes (X11)" xload XEYESR.BIN'
  on_disk XCALCR.BIN && echo 'prog "XCalc (X11)" app XCALCR.BIN'
  echo 'separator'
  echo 'menufile "Tool bar" folder toolbar'
} > "$M"

T="$OUT/toolbar"
{
  echo "# /ICEWM/toolbar -- GENERATED by src/user/x11sess/gen-icewm-menu.sh"
  for a in CONSOLE.BIN FILES.BIN; do
    on_disk "$a" && echo "prog \"$(label "$a")\" app HBHOST.BIN $a"
  done
  on_disk XFILES.BIN && echo 'prog "Files (X11)" folder XFILES.BIN'
  on_disk XEYESR.BIN && echo 'prog "XEyes" xload XEYESR.BIN'
  on_disk XCALCR.BIN && echo 'prog "XCalc" app XCALCR.BIN'
} > "$T"

na=$(grep -c 'HBHOST.BIN' "$M" || true)
echo "[icewm-menu] $M: $na native entries ($(printf '%s\n' $APPS | wc -l) pinned apps, $(printf '%s\n' $GAMES | wc -l) pinned games)"
