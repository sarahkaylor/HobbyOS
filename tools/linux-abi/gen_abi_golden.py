#!/usr/bin/env python3
"""tools/linux-abi/gen_abi_golden.py — record Linux ground truth for the compat ABI.

Emits two committed-but-generated golden files:

  tests/fixtures/abi/linux_syscalls.golden  syscall name -> number, from <sys/syscall.h>
  tests/fixtures/abi/linux_errno.golden     errno name   -> value,   from <errno.h>

The names come from OUR headers (src/include/linux_syscall.h, src/include/errno.h),
the values come from the LINUX build host's headers — so a typo in our table is a
test failure in src/host/linux_abi_test.c.  Regenerating requires a Linux x86_64
host with a C compiler; *running* the test does not (the goldens are committed),
which keeps the T1 tier green on macOS too.

  python3 tools/linux-abi/gen_abi_golden.py [--check]
"""
import argparse
import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", ".."))
OUTDIR = os.path.join(REPO, "tests", "fixtures", "abi")

PROV = ("# generated by tools/linux-abi/gen_abi_golden.py from the Linux x86_64\n"
        "# headers on {host} ({uname}); values are the kernel's, names are ours.\n"
        "# Regenerate on a Linux x86_64 host; never hand-edit.\n")


def syscall_names(path):
    """src/include/linux_syscall.h: L_SYS_foo -> ("foo", "SYS_foo").

    ALL-CAPS rows are not syscalls (L_SYS_MAX_KNOWN is a bound, L_ARCH_* / L_O_*
    use other prefixes) — including one here compiles a `SYS_MAX_KNOWN` that does
    not exist."""
    out = []
    pat = re.compile(r"^#define\s+L_SYS_(\w+)\s+(\d+)\s*(?:/\*.*)?$")
    for line in open(path, encoding="utf-8"):
        m = pat.match(line)
        if m and not m.group(1).isupper():
            out.append((m.group(1), "SYS_" + m.group(1)))
    return out


def errno_names(path):
    """src/include/errno.h: EFOO -> ("EFOO", "EFOO").

    Alias rows with no literal value (EWOULDBLOCK EAGAIN) are skipped — they are
    not independently measurable."""
    out = []
    # trailing comments are common in errno.h ("EMSGSIZE 90 /* P4 design D13 */")
    pat = re.compile(r"^#define\s+(E[A-Z0-9_]+)\s+(\d+)\s*(?:/\*.*)?$")
    for line in open(path, encoding="utf-8"):
        m = pat.match(line)
        if m:
            out.append((m.group(1), m.group(1)))
    return out


def run(pairs, include):
    """pairs: [(golden_name, c_expression)]; prints the Linux value of each."""
    src = "#include <stdio.h>\n#include <" + include + ">\nint main(void){\n"
    for name, expr in pairs:
        src += f'  printf("%s %ld\\n", "{name}", (long)({expr}));\n'
    src += "  return 0;\n}\n"
    with tempfile.TemporaryDirectory() as d:
        c, exe = os.path.join(d, "g.c"), os.path.join(d, "g")
        open(c, "w").write(src)
        r = subprocess.run([os.environ.get("CC", "cc"), "-o", exe, c],
                           capture_output=True, text=True)
        if r.returncode != 0:
            # show the first failing name, not just cc's noise
            for name, expr in pairs:
                probe = "#include <stdio.h>\n#include <" + include + ">\nint main(void){(void)(" + expr + ");return 0;}\n"
                open(c, "w").write(probe)
                rr = subprocess.run([os.environ.get("CC", "cc"), "-o", exe, c],
                                    capture_output=True, text=True)
                if rr.returncode != 0:
                    print(f"unknown name in {include}: {name} ({expr})", file=sys.stderr)
                    print(rr.stderr.splitlines()[0] if rr.stderr else "", file=sys.stderr)
                    raise SystemExit(3)
            raise SystemExit(3)
        out = subprocess.run([exe], check=True, capture_output=True, text=True).stdout
    rows = []
    for line in out.splitlines():
        name, val = line.split()
        rows.append((name, int(val)))
    return sorted(rows, key=lambda r: (r[1], r[0]))


def write_golden(path, rows, header_note):
    uname = subprocess.run(["uname", "-srm"], capture_output=True, text=True).stdout.strip()
    host = os.uname().nodename
    body = " ".join([PROV.format(host=host, uname=uname), f"# {header_note}\n"])
    body += "".join(f"{n} {v}\n" for n, v in rows)
    open(path, "w", encoding="utf-8").write(body)
    return body


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--check", action="store_true")
    a = p.parse_args()
    os.makedirs(OUTDIR, exist_ok=True)
    if os.uname().sysname != "Linux":
        print("gen_abi_golden.py must run on a Linux host (it reads Linux headers)", file=sys.stderr)
        return 2

    sc_path = os.path.join(OUTDIR, "linux_syscalls.golden")
    er_path = os.path.join(OUTDIR, "linux_errno.golden")
    sc = run(syscall_names(os.path.join(REPO, "src/include/linux_syscall.h")), "sys/syscall.h")
    er = run(errno_names(os.path.join(REPO, "src/include/errno.h")), "errno.h")

    if a.check:
        problems = []
        for path, rows in ((sc_path, sc), (er_path, er)):
            cur = {}
            for line in open(path, encoding="utf-8"):
                if line.startswith("#"):
                    continue
                k, v = line.split()
                cur[k] = int(v)
            for n, v in rows:
                if cur.get(n) != v:
                    problems.append(f"{os.path.basename(path)}: {n} golden={cur.get(n)} linux={v}")
        if problems:
            print("\n".join(problems))
            print("goldens are STALE vs this Linux box — re-run without --check to refresh")
            return 1
        print(f"goldens match this Linux box ({len(sc)} syscalls, {len(er)} errno)")
        return 0

    write_golden(sc_path, sc, "syscall numbers (x86_64) that src/include/linux_syscall.h must match")
    write_golden(er_path, er, "errno values that src/include/errno.h must match")
    print(f"wrote {sc_path} ({len(sc)} rows)\nwrote {er_path} ({len(er)} rows)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
