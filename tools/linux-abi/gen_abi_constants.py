#!/usr/bin/env python3
"""tools/linux-abi/gen_abi_constants.py — record Linux ground truth for the
compat L_* constants in src/include/linux_syscall.h.

docs/linux-abi.md §3 promises the O_*/PROT_*/MAP_*/POLL*/F_*/W*/SIG*/SA_*/TC*/
TIOC*/DT_*/EV_*/KEY_*/ABS_*/REL_* constants are asserted by the M1 T4 suite.
The syscall-number/errno goldens (linux_abi_test.c) and the struct-layout golden
(linux_layout_test.c) exist; the *constants* had no lock.  This closes the gap:

  tests/fixtures/abi/linux_constants.golden
    compat-name -> Linux-true value, measured on a real Linux x86_64 box.
    E.g. "O_CREAT 64", "PROT_READ 1", "MAP_ANONYMOUS 0x20", "TCGETS 0x5401".

The names are the *un-prefixed* forms; src/host/linux_abi_constants_test.c maps
each back to our L_* macro and asserts it equals the golden value (GB-014/GB-015,
M1 T4 suite), so a transposed digit in the header is a test failure.

  python3 tools/linux-abi/gen_abi_constants.py [--check]
"""
import argparse
import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", ".."))
OUTDIR = os.path.join(REPO, "tests", "fixtures", "abi")
SYS_HDR = os.path.join(REPO, "src", "include", "linux_syscall.h")

PROV = ("# generated by tools/linux-abi/gen_abi_constants.py from the Linux x86_64\n"
        "# headers on {host} ({uname}); values are the kernel's, names are ours.\n"
        "# Regenerate on a Linux x86_64 host; never hand-edit.\n")

# (golden name, C expression, include).  The C expression compiles on a Linux
# host and yields the authoritative value; each name must have a matching
# `#define L_<name>` in src/include/linux_syscall.h.
# fmt: off
ROWS = [
    # open flags (fcntl.h)
    ("O_RDONLY", "O_RDONLY", "fcntl.h"), ("O_WRONLY", "O_WRONLY", "fcntl.h"),
    ("O_RDWR", "O_RDWR", "fcntl.h"), ("O_CREAT", "O_CREAT", "fcntl.h"),
    ("O_EXCL", "O_EXCL", "fcntl.h"), ("O_TRUNC", "O_TRUNC", "fcntl.h"),
    ("O_APPEND", "O_APPEND", "fcntl.h"), ("O_NONBLOCK", "O_NONBLOCK", "fcntl.h"),
    ("O_DIRECTORY", "O_DIRECTORY", "fcntl.h"), ("O_CLOEXEC", "O_CLOEXEC", "fcntl.h"),
    # memory protection / mapping (sys/mman.h)
    ("PROT_READ", "PROT_READ", "sys/mman.h"), ("PROT_WRITE", "PROT_WRITE", "sys/mman.h"),
    ("PROT_EXEC", "PROT_EXEC", "sys/mman.h"),
    ("MAP_SHARED", "MAP_SHARED", "sys/mman.h"), ("MAP_PRIVATE", "MAP_PRIVATE", "sys/mman.h"),
    ("MAP_FIXED", "MAP_FIXED", "sys/mman.h"), ("MAP_ANONYMOUS", "MAP_ANONYMOUS", "sys/mman.h"),
    # seek / clock / poll (stdio.h, time.h, poll.h)
    ("SEEK_SET", "SEEK_SET", "stdio.h"), ("SEEK_CUR", "SEEK_CUR", "stdio.h"),
    ("SEEK_END", "SEEK_END", "stdio.h"),
    ("CLOCK_REALTIME", "CLOCK_REALTIME", "time.h"), ("CLOCK_MONOTONIC", "CLOCK_MONOTONIC", "time.h"),
    ("POLLIN", "POLLIN", "poll.h"), ("POLLOUT", "POLLOUT", "poll.h"),
    ("POLLERR", "POLLERR", "poll.h"), ("POLLHUP", "POLLHUP", "poll.h"),
    # wait / signal (sys/wait.h, signal.h)
    ("WNOHANG", "WNOHANG", "sys/wait.h"), ("WUNTRACED", "WUNTRACED", "sys/wait.h"),
    ("SIG_BLOCK", "SIG_BLOCK", "signal.h"), ("SIG_UNBLOCK", "SIG_UNBLOCK", "signal.h"),
    ("SIG_SETMASK", "SIG_SETMASK", "signal.h"),
    # termios / ioctl
    ("TCGETS", "TCGETS", "sys/ioctl.h"), ("TCSETS", "TCSETS", "sys/ioctl.h"),
    ("TIOCGWINSZ", "TIOCGWINSZ", "sys/ioctl.h"),
    ("FIONREAD", "FIONREAD", "sys/ioctl.h"), ("FIONBIO", "FIONBIO", "sys/ioctl.h"),
]
# fmt: on


def run_one(expr, include):
    src = (f"#define _GNU_SOURCE\n#include <{include}>\n"
           f"#include <stdio.h>\nint main(void){{ printf(\"%ld\\n\", (long)({expr})); return 0; }}\n")
    with tempfile.TemporaryDirectory() as d:
        c, exe = os.path.join(d, "g.c"), os.path.join(d, "g")
        open(c, "w").write(src)
        cc = os.environ.get("CC", "cc")
        r = subprocess.run([cc, "-o", exe, c], capture_output=True, text=True)
        if r.returncode != 0:
            print(f"compile failed for {expr} (include {include}):\n{r.stderr[:400]}", file=sys.stderr)
            raise SystemExit(3)
        return int(subprocess.run([exe], check=True, capture_output=True, text=True).stdout.strip())


def header_has(name):
    """True if src/include/linux_syscall.h defines L_<name>."""
    pat = re.compile(r"^#define\s+L_" + re.escape(name) + r"\s+")
    for line in open(SYS_HDR, encoding="utf-8"):
        if pat.match(line):
            return True
    return False


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--check", action="store_true")
    a = p.parse_args()
    os.makedirs(OUTDIR, exist_ok=True)
    if os.uname().sysname != "Linux":
        print("must run on a Linux host (reads Linux headers)", file=sys.stderr)
        return 2

    path = os.path.join(OUTDIR, "linux_constants.golden")
    missing = [n for n, _, _ in ROWS if not header_has(n)]
    if missing:
        print(f"ERROR: src/include/linux_syscall.h lacks L_* for: {missing}", file=sys.stderr)
        print("Add the #define L_<name> row, then re-run.", file=sys.stderr)
        return 3

    # measure
    measured = {}
    for name, expr, inc in ROWS:
        measured[name] = run_one(expr, inc)

    if a.check:
        problems = []
        for line in open(path, encoding="utf-8"):
            if line.startswith("#"):
                continue
            k, v = line.split()
            if measured.get(k) is None:
                problems.append(f"{k}: not measured by this run")
            elif int(v) != measured[k]:
                problems.append(f"{k}: golden={v} linux={measured[k]}")
        if problems:
            print("\n".join(problems))
            print("linux_constants.golden is STALE — re-run without --check to refresh")
            return 1
        print(f"linux_constants.golden matches this Linux box ({len(measured)} constants)")
        return 0

    # write
    uname = subprocess.run(["uname", "-srm"], capture_output=True, text=True).stdout.strip()
    host = os.uname().nodename
    body = " ".join([PROV.format(host=host, uname=uname), "\n"])
    for name, _, _ in ROWS:
        body += f"{name} {measured[name]}\n"
    open(path, "w", encoding="utf-8").write(body)
    print(f"wrote {path} ({len(measured)} constants)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
