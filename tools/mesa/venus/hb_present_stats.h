/*
 * hb_present_stats.h -- the HobbyOS present-cost instrument (Cyberpunk P7,
 * lane C6-p7; docs/cp-p7.md §3).  Copied into Mesa's src/vulkan/wsi/ by
 * tools/mesa/venus/build.sh and included by wsi_common.c (which defines the
 * one global: HB_PSTATS_DEFINE) and wsi_common_x11.c.
 *
 * The RimWorld [HBT] idea (docs/l88-fps-report.md) for Vulkan: every present
 * is split into the stages that can cost time, measured with the TSC (the
 * guest's CLOCK_MONOTONIC ticks at 1 ms), and one row per window
 * (HB_PRESENT_STATS_MS, default 2000; 0 = off) goes to stderr:
 *
 *   [HBP] pid=P n=N fps=F path=scanout|putimage|mixed
 *         acq=avg/max sub=avg/max wait=avg/max flip=avg/max geom=avg/max
 *         set=avg flush=avg (kernel round trips of a scanout flip) us
 *         scanout=S putimage=U refused=R
 *
 *   acq    vkAcquireNextImageKHR (wsi_common_acquire_next_image2), app thread
 *   sub    vkQueuePresentKHR minus `wait`: the blit / semaphore submit and
 *          the hand-off to the WSI queue thread
 *   wait   the software WSI's CPU wait for the frame's fence (the GPU
 *          finishing the frame + its blit), inside vkQueuePresentKHR
 *   flip   the WSI queue thread's present: GPU_IOC_SCANOUT_BLOB, or
 *          xcb_put_image of the whole image
 *   geom   the xcb_get_geometry round trip after it (OUT_OF_DATE check)
 *   set/flush  what the kernel measured inside the scanout ioctl
 *
 * Every number is a per-window average and maximum in microseconds.  Cost
 * of the instrument: a few rdtsc and atomic adds per present and one write(2)
 * per window.
 */
#ifndef HB_PRESENT_STATS_H
#define HB_PRESENT_STATS_H

#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <unistd.h>
#include "util/os_time.h"
#include <string.h>
#include "hb_env_defaults.h" /* generated by build.sh: HB_ENV_DEFAULTS "K=V;K2=V2" */

/* getenv() with build-time defaults: Wine's processes get the fixed
 * environment of their launcher, so a build can bake a default
 * (HB_MESA_ENV_DEFAULTS at build time) that the environment still
 * overrides.  The value runs to the next ';' (callers parse a prefix). */
static inline const char *
hb_getenv(const char *k)
{
   const char *e = getenv(k);
   if (e)
      return e;
   static const char d[] = HB_ENV_DEFAULTS;
   const size_t kl = strlen(k);
   for (const char *p = d; *p;) {
      const char *end = strchr(p, ';');
      if (!end)
         end = p + strlen(p);
      if ((size_t)(end - p) > kl && !strncmp(p, k, kl) && p[kl] == '=')
         return p + kl + 1;
      p = *end ? end + 1 : end;
   }
   return NULL;
}

enum {
   HB_PS_ACQ,
   HB_PS_SUB,
   HB_PS_WAIT,
   HB_PS_FLIP,
   HB_PS_GEOM,
   HB_PS_SET,
   HB_PS_FLUSH,
   HB_PS_N
};

/* C6-present (docs/cp-present.md): where venus' own threads wait, per window
 * ([HBV] row, printed next to [HBP]).  Every entry is count + TSC sum + max. */
enum {
   HB_VS_RING,   /* vn_ring_wait_seqno on the instance ring (a reply)        */
   HB_VS_TLS,    /* vn_ring_wait_seqno on a thread's TLS ring (a reply)      */
   HB_VS_SPACE,  /* waiting for ring space                                   */
   HB_VS_SLP_R,  /* vn_relax sleeps: ring / TLS ring seqno                   */
   HB_VS_SLP_O,  /* vn_relax sleeps: space, semaphore, query                 */
   HB_VS_YIELD,  /* vn_relax thrd_yield                                      */
   HB_VS_NOTIFY, /* vkNotifyRingMESA (renderer submit_simple, unfenced)      */
   HB_VS_SUBF,   /* hobbyos_submit with fence(s): GPU_IOC_SUBMIT2            */
   HB_VS_SUBU,   /* hobbyos_submit without fence (cs only)                   */
   HB_VS_WAIT,   /* hobbyos_wait: vkWaitForFences/vkWaitSemaphores/...       */
   HB_VS_FWAIT,  /* GPU_IOC_FENCE_WAIT2 with a timeout (inside WAIT)         */
   HB_VS_QSUB,   /* app-thread vkQueueSubmit/2/BindSparse                    */
   HB_VS_PWAIT,  /* vkWaitForPresentKHR / vkWaitForPresent2KHR               */
   HB_VS_N
};
/* per thread: renderer waits (w), queue submits (q), present waits (p) */
#define HB_VS_TIDS 32
struct hb_vtid {
   int32_t tid;  /* 0 = free */
   uint64_t cnt[3], sum[3];
};
#define HB_VS_CMDS 64
struct hb_vcmd {
   uint32_t type1;  /* VkCommandTypeEXT + 1, 0 = free */
   uint64_t cnt, sum, max;
};

struct hb_pstats {
   uint64_t vsum[HB_VS_N], vmax[HB_VS_N], vcnt[HB_VS_N];
   struct hb_vcmd vcmd[HB_VS_CMDS];  /* replies waited for, by command type */
   struct hb_vtid vtid[HB_VS_TIDS];
   int state;                  /* 0 unread env, 1 on, -1 off */
   uint64_t window_ms;
   uint64_t tsc0, ns0;         /* calibration origin */
   uint64_t win_tsc, win_ns;   /* current window start */
   uint64_t sum[HB_PS_N], max[HB_PS_N], cnt[HB_PS_N];  /* TSC cycles */
   uint64_t presents, scanout, putimage, refused;
   uint64_t total_presents;
};

#ifdef HB_PSTATS_DEFINE
struct hb_pstats hb_pstats;
#else
extern struct hb_pstats hb_pstats;
#endif

static inline uint64_t
hb_tsc(void)
{
#if defined(__x86_64__)
   uint32_t lo, hi;
   __asm__ volatile("rdtsc" : "=a"(lo), "=d"(hi));
   return ((uint64_t)hi << 32) | lo;
#else
   return (uint64_t)os_time_get_nano();
#endif
}

static inline int
hb_pstats_on(void)
{
   struct hb_pstats *s = &hb_pstats;
   int st = __atomic_load_n(&s->state, __ATOMIC_ACQUIRE);
   if (st)
      return st > 0;
   const char *e = hb_getenv("HB_PRESENT_STATS_MS");
   long ms = e ? strtol(e, NULL, 10) : 2000;
   s->window_ms = ms > 0 ? (uint64_t)ms : 0;
   s->tsc0 = s->win_tsc = hb_tsc();
   s->ns0 = s->win_ns = (uint64_t)os_time_get_nano();
   __atomic_store_n(&s->state, ms > 0 ? 1 : -1, __ATOMIC_RELEASE);
   return ms > 0;
}

/* One stage sample, in TSC cycles. */
static inline void
hb_pstats_add(int k, uint64_t cyc)
{
   struct hb_pstats *s = &hb_pstats;
   if (!hb_pstats_on())
      return;
   __atomic_fetch_add(&s->sum[k], cyc, __ATOMIC_RELAXED);
   __atomic_fetch_add(&s->cnt[k], 1, __ATOMIC_RELAXED);
   uint64_t m = __atomic_load_n(&s->max[k], __ATOMIC_RELAXED);
   while (cyc > m && !__atomic_compare_exchange_n(&s->max[k], &m, cyc, 1, __ATOMIC_RELAXED,
                                                  __ATOMIC_RELAXED))
      ;
}

static inline void
hb_vmax(uint64_t *mp, uint64_t cyc)
{
   uint64_t m = __atomic_load_n(mp, __ATOMIC_RELAXED);
   while (cyc > m && !__atomic_compare_exchange_n(mp, &m, cyc, 1, __ATOMIC_RELAXED,
                                                  __ATOMIC_RELAXED))
      ;
}

/* C6-present: one venus-side wait/submit sample, in TSC cycles. */
static inline void
hb_vstats_add(int k, uint64_t cyc)
{
   struct hb_pstats *s = &hb_pstats;
   if (!hb_pstats_on())
      return;
   __atomic_fetch_add(&s->vsum[k], cyc, __ATOMIC_RELAXED);
   __atomic_fetch_add(&s->vcnt[k], 1, __ATOMIC_RELAXED);
   hb_vmax(&s->vmax[k], cyc);
}

#include <sys/syscall.h>
/* C6-present: per-thread totals; which: 0 wait, 1 queue submit, 2 present wait. */
static inline void
hb_vtid_add(int which, uint64_t cyc)
{
   struct hb_pstats *s = &hb_pstats;
   if (!hb_pstats_on())
      return;
   static __thread int32_t my_tid;
   if (!my_tid)
      my_tid = (int32_t)syscall(SYS_gettid);
   const int32_t t = my_tid;
   for (uint32_t i = 0; i < HB_VS_TIDS; i++) {
      struct hb_vtid *e = &s->vtid[((uint32_t)t + i) % HB_VS_TIDS];
      int32_t cur = __atomic_load_n(&e->tid, __ATOMIC_ACQUIRE);
      if (cur == 0) {
         int32_t z = 0;
         cur = __atomic_compare_exchange_n(&e->tid, &z, t, 0, __ATOMIC_ACQ_REL, __ATOMIC_ACQUIRE)
                  ? t
                  : z;
      }
      if (cur != t)
         continue;
      __atomic_fetch_add(&e->cnt[which], 1, __ATOMIC_RELAXED);
      __atomic_fetch_add(&e->sum[which], cyc, __ATOMIC_RELAXED);
      return;
   }
}

/* C6-present: a reply waited for, by its command type (first dword of the
 * command stream). */
static inline void
hb_vstats_cmd(uint32_t type, uint64_t cyc)
{
   struct hb_pstats *s = &hb_pstats;
   if (!hb_pstats_on())
      return;
   const uint32_t t1 = type + 1;
   for (uint32_t i = 0; i < HB_VS_CMDS; i++) {
      struct hb_vcmd *c = &s->vcmd[(type + i) % HB_VS_CMDS];
      uint32_t cur = __atomic_load_n(&c->type1, __ATOMIC_ACQUIRE);
      if (cur == 0) {
         uint32_t z = 0;
         if (!__atomic_compare_exchange_n(&c->type1, &z, t1, 0, __ATOMIC_ACQ_REL,
                                          __ATOMIC_ACQUIRE))
            cur = z;
         else
            cur = t1;
      }
      if (cur != t1)
         continue;
      __atomic_fetch_add(&c->cnt, 1, __ATOMIC_RELAXED);
      __atomic_fetch_add(&c->sum, cyc, __ATOMIC_RELAXED);
      hb_vmax(&c->max, cyc);
      return;
   }
}

/* A kernel-measured stage, in microseconds (converted with the current
 * calibration; before the first window it is stored as cycles at 1 GHz and
 * the first row is approximate). */
static inline void
hb_pstats_add_us(int k, uint32_t us)
{
   struct hb_pstats *s = &hb_pstats;
   if (!hb_pstats_on())
      return;
   uint64_t dt = hb_tsc() - s->tsc0, dn = (uint64_t)os_time_get_nano() - s->ns0;
   double cpn = dn > 100000000ull ? (double)dt / (double)dn : 1.0;
   hb_pstats_add(k, (uint64_t)((double)us * 1000.0 * cpn));
}

/* After each flip (WSI queue thread): count it and, once per window, print
 * the row and start a new window.  path: 1 scanout, 2 putimage; refused:
 * the kernel said not now (fell back to putimage). */
static inline void
hb_pstats_present(int path, int refused)
{
   struct hb_pstats *s = &hb_pstats;
   if (!hb_pstats_on())
      return;
   __atomic_fetch_add(&s->presents, 1, __ATOMIC_RELAXED);
   __atomic_fetch_add(path == 1 ? &s->scanout : &s->putimage, 1, __ATOMIC_RELAXED);
   if (refused)
      __atomic_fetch_add(&s->refused, 1, __ATOMIC_RELAXED);
   uint64_t now_ns = (uint64_t)os_time_get_nano();
   if (now_ns - s->win_ns < s->window_ms * 1000000ull)
      return;
   uint64_t now_tsc = hb_tsc();
   double cpn = (double)(now_tsc - s->tsc0) / (double)(now_ns - s->ns0 ? now_ns - s->ns0 : 1);
   double win_s = (double)(now_tsc - s->win_tsc) / cpn / 1e9;
   uint64_t n = __atomic_exchange_n(&s->presents, 0, __ATOMIC_RELAXED);
   uint64_t so = __atomic_exchange_n(&s->scanout, 0, __ATOMIC_RELAXED);
   uint64_t pu = __atomic_exchange_n(&s->putimage, 0, __ATOMIC_RELAXED);
   uint64_t rf = __atomic_exchange_n(&s->refused, 0, __ATOMIC_RELAXED);
   double avg[HB_PS_N], mx[HB_PS_N];
   for (int k = 0; k < HB_PS_N; k++) {
      uint64_t c = __atomic_exchange_n(&s->cnt[k], 0, __ATOMIC_RELAXED);
      uint64_t su = __atomic_exchange_n(&s->sum[k], 0, __ATOMIC_RELAXED);
      uint64_t m = __atomic_exchange_n(&s->max[k], 0, __ATOMIC_RELAXED);
      avg[k] = c ? (double)su / (double)c / cpn / 1000.0 : 0.0;
      mx[k] = (double)m / cpn / 1000.0;
   }
   s->total_presents += n;
   s->win_tsc = now_tsc;
   s->win_ns = now_ns;
   char row[512];
   int len = snprintf(row, sizeof row,
                      "[HBP] pid=%d n=%llu fps=%.1f path=%s acq=%.0f/%.0f sub=%.0f/%.0f "
                      "wait=%.0f/%.0f flip=%.0f/%.0f geom=%.0f/%.0f set=%.0f flush=%.0f us "
                      "scanout=%llu putimage=%llu refused=%llu total=%llu\n",
                      (int)getpid(), (unsigned long long)n, win_s > 0 ? n / win_s : 0.0,
                      so && pu ? "mixed" : so ? "scanout" : "putimage", avg[HB_PS_ACQ],
                      mx[HB_PS_ACQ], avg[HB_PS_SUB], mx[HB_PS_SUB], avg[HB_PS_WAIT],
                      mx[HB_PS_WAIT], avg[HB_PS_FLIP], mx[HB_PS_FLIP], avg[HB_PS_GEOM],
                      mx[HB_PS_GEOM], avg[HB_PS_SET], avg[HB_PS_FLUSH], (unsigned long long)so,
                      (unsigned long long)pu, (unsigned long long)rf,
                      (unsigned long long)s->total_presents);
   if (len > 0)
      (void)!write(2, row, (size_t)(len < (int)sizeof row ? len : (int)sizeof row - 1));

   /* C6-present: [HBV] -- the same window's venus waits.  Per entry:
    * count / avg us / total ms (max us for the waits). */
   static const char *const vn[HB_VS_N] = { "ring", "tls", "space", "slpR", "slpO", "yield",
                                            "ntf", "subF", "subU", "wait", "fwait", "qsub",
                                            "pwait" };
   char vrow[2000];
   int vl = snprintf(vrow, sizeof vrow, "[HBV] pid=%d n=%llu win_ms=%.0f", (int)getpid(),
                     (unsigned long long)n, win_s * 1000.0);
   for (int k = 0; k < HB_VS_N && vl > 0 && vl < (int)sizeof vrow - 64; k++) {
      uint64_t c = __atomic_exchange_n(&s->vcnt[k], 0, __ATOMIC_RELAXED);
      uint64_t su = __atomic_exchange_n(&s->vsum[k], 0, __ATOMIC_RELAXED);
      uint64_t m = __atomic_exchange_n(&s->vmax[k], 0, __ATOMIC_RELAXED);
      vl += snprintf(vrow + vl, sizeof vrow - vl, " %s=%llu/%.0f/%.1f/%.0f", vn[k],
                     (unsigned long long)c, c ? (double)su / (double)c / cpn / 1000.0 : 0.0,
                     (double)su / cpn / 1e6, (double)m / cpn / 1000.0);
   }
   /* the six command types whose replies cost the most this window */
   struct { uint32_t t; uint64_t c, su, m; } top[6] = { { 0 } };
   for (int i = 0; i < HB_VS_CMDS; i++) {
      struct hb_vcmd *c = &s->vcmd[i];
      uint32_t t1 = __atomic_load_n(&c->type1, __ATOMIC_ACQUIRE);
      if (!t1)
         continue;
      uint64_t cc = __atomic_exchange_n(&c->cnt, 0, __ATOMIC_RELAXED);
      uint64_t su = __atomic_exchange_n(&c->sum, 0, __ATOMIC_RELAXED);
      uint64_t m = __atomic_exchange_n(&c->max, 0, __ATOMIC_RELAXED);
      if (!cc)
         continue;
      for (int j = 0; j < 6; j++) {
         if (su > top[j].su) {
            for (int q = 5; q > j; q--)
               top[q] = top[q - 1];
            top[j].t = t1 - 1;
            top[j].c = cc;
            top[j].su = su;
            top[j].m = m;
            break;
         }
      }
   }
   if (vl > 0 && vl < (int)sizeof vrow - 16)
      vl += snprintf(vrow + vl, sizeof vrow - vl, " cmd");
   for (int j = 0; j < 6 && top[j].c && vl > 0 && vl < (int)sizeof vrow - 48; j++)
      vl += snprintf(vrow + vl, sizeof vrow - vl, " %u:%llu/%.0f/%.0f", top[j].t,
                     (unsigned long long)top[j].c, (double)top[j].su / top[j].c / cpn / 1000.0,
                     (double)top[j].m / cpn / 1000.0);
   /* the threads that waited longest this window: w/q/p = count/ms */
   struct { int32_t t; uint64_t c[3], su[3], key; } tt[6] = { { 0 } };
   for (int i = 0; i < HB_VS_TIDS; i++) {
      struct hb_vtid *e = &s->vtid[i];
      int32_t t = __atomic_load_n(&e->tid, __ATOMIC_ACQUIRE);
      if (!t)
         continue;
      uint64_t c[3], su[3];
      for (int w = 0; w < 3; w++) {
         c[w] = __atomic_exchange_n(&e->cnt[w], 0, __ATOMIC_RELAXED);
         su[w] = __atomic_exchange_n(&e->sum[w], 0, __ATOMIC_RELAXED);
      }
      const uint64_t key = su[0] + su[1] + su[2];
      if (!key)
         continue;
      for (int j = 0; j < 6; j++) {
         if (key > tt[j].key) {
            for (int q = 5; q > j; q--)
               tt[q] = tt[q - 1];
            tt[j].t = t;
            tt[j].key = key;
            for (int w = 0; w < 3; w++) {
               tt[j].c[w] = c[w];
               tt[j].su[w] = su[w];
            }
            break;
         }
      }
   }
   if (vl > 0 && vl < (int)sizeof vrow - 16)
      vl += snprintf(vrow + vl, sizeof vrow - vl, " tid");
   for (int j = 0; j < 6 && tt[j].key && vl > 0 && vl < (int)sizeof vrow - 96; j++)
      vl += snprintf(vrow + vl, sizeof vrow - vl, " %d:w=%llu/%.1f,q=%llu/%.1f,p=%llu/%.1f", tt[j].t,
                     (unsigned long long)tt[j].c[0], (double)tt[j].su[0] / cpn / 1e6,
                     (unsigned long long)tt[j].c[1], (double)tt[j].su[1] / cpn / 1e6,
                     (unsigned long long)tt[j].c[2], (double)tt[j].su[2] / cpn / 1e6);
   if (vl > 0 && vl < (int)sizeof vrow - 1) {
      vrow[vl++] = '\n';
      (void)!write(2, vrow, (size_t)vl);
   }
}

#endif /* HB_PRESENT_STATS_H */
