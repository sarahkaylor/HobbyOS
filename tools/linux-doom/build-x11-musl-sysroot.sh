#!/usr/bin/env bash
# build-x11-musl-sysroot.sh — assemble a musl-linked STATIC libX11/libXext
# sysroot for the HobbyOS DOOM builds.
#
# Why this exists
# ---------------
# docs/linux-abi.md says the HobbyOS compat track accepts static-PIE musl
# binaries.  Debian has no musl-built libX11.a, and libX11 is far too big to
# hand-port, so we take Alpine's static archives (Alpine *is* musl) plus the
# matching headers, and build the one missing archive, libXau, from source
# (Alpine ships libXau only as a shared object; libxcb.a needs XauGetBestAuthByAddr
# for XOpenDisplay's MIT-MAGIC-COOKIE path).
#
# Outputs (all under $CACHE, default ~/.cache/hobbyos-doom):
#   $CACHE/x11-musl-sysroot/        usr/include + usr/lib/*.a
#   $CACHE/x11-musl.env             sourceable: X11_MUSL_SYSROOT/CFLAGS/LIBS
#
# Idempotent: re-running re-verifies the pinned sha256s and skips work.
set -euo pipefail

CACHE="${HOBBYOS_DOOM_CACHE:-$HOME/.cache/hobbyos-doom}"
DL="$CACHE/dl"
SYSROOT="$CACHE/x11-musl-sysroot"
BROOT="$CACHE/build"
ENVFILE="$CACHE/x11-musl.env"
ALPINE_BASE="${ALPINE_BASE:-https://dl-cdn.alpinelinux.org/alpine/v3.24/main/x86_64}"
XAU_URL="${XAU_URL:-https://xorg.freedesktop.org/archive/individual/lib/libXau-1.0.12.tar.xz}"

mkdir -p "$DL" "$BROOT"

# Pinned Alpine 3.24 packages (musl build of X.Org) and their sha256.
# Regenerate the list with: curl -s $ALPINE_BASE/ | grep libx11
PKGS=(
  "libx11-static-1.8.14-r0.apk      0d7f1f3f7aaf66052ea7793b83ca7068d7c24d9751dc1a85eb7dfe33b806ca6b"
  "libx11-dev-1.8.14-r0.apk         e6f72a43c12c734fb76bee5e01856f42dbefc37cc4bacb52667fe31d858238fc"
  "libxext-static-1.3.7-r0.apk      7fdf6fb8f8fd38dd00aa8af477a36d975e0382fc7d0955a92493af5ce41e3c4f"
  "libxext-dev-1.3.7-r0.apk         1ece3bac09c39b7b90baa87df1f2ecf7d2593a466ed18431d433bd16424438f9"
  "libxcb-static-1.17.0-r2.apk      e4ce28537cad6ee1994ce9311b42c201dc3e09cafb249c3bb6f3027d35d95611"
  "libxcb-dev-1.17.0-r2.apk         6658de0d8836c0e60744edf4e315bf006cd18d24f0539e58b3f70e2eae0b93c7"
  "libxau-dev-1.0.12-r0.apk         3c5923a390aa2140fd1bc40d06fa744e9a300d95649ffb2da6a306f477aeecf3"
  "libxdmcp-dev-1.1.5-r1.apk        fe5105753cd02434813aa2ff0502024340ad6094dc858b42f6a88c6e2f13f1e4"
  "xorgproto-2025.1-r0.apk          8e43324c60aa227a1a335aef357dc2c0c26afcc536952f992b4a32293d230d76"
  "xtrans-1.6.0-r0.apk              a2d7e9227e5f6ddcb7819d8f1bd50a17673f5a87986d8a98118ad14e3377be4a"
)
XAU_SHA256="74d0e4dfa3d39ad8939e99bda37f5967aba528211076828464d2777d477fc0fb"

fetch() { # fetch <url> <dest> <sha256>
  local url="$1" dest="$2" want="$3"
  if [[ -f "$dest" ]] && echo "$want  $dest" | sha256sum -c --status -; then
    echo "[x11] cached   $(basename "$dest")"
    return
  fi
  echo "[x11] fetching $(basename "$dest")"
  curl -fsSL --retry 3 -o "$dest.part" "$url"
  echo "$want  $dest.part" | sha256sum -c --status - || {
    echo "[x11] ERROR: sha256 mismatch for $url" >&2; rm -f "$dest.part"; exit 1; }
  mv "$dest.part" "$dest"
}

for entry in "${PKGS[@]}"; do
  set -- $entry
  fetch "$ALPINE_BASE/$1" "$DL/$1" "$2"
done
fetch "$XAU_URL" "$DL/libXau-1.0.12.tar.xz" "$XAU_SHA256"

rm -rf "$SYSROOT"; mkdir -p "$SYSROOT"
for entry in "${PKGS[@]}"; do
  set -- $entry
  gzip -dc "$DL/$1" | tar -x --warning=no-unknown-keyword -C "$SYSROOT"
done
echo "[x11] extracted ${#PKGS[@]} packages into $SYSROOT"

# --- libXau (static, musl) -------------------------------------------------
# Alpine has no libXau.a; build it from the X.Org release tarball.
if [[ ! -f "$SYSROOT/usr/lib/libXau.a" ]]; then
  rm -rf "$BROOT/libXau-1.0.12"
  tar -xf "$DL/libXau-1.0.12.tar.xz" -C "$BROOT"
  (
    cd "$BROOT/libXau-1.0.12"
    # xorgproto headers come from the Alpine sysroot, not the (glibc) host.
    ./configure --host=x86_64-linux-musl CC=musl-gcc \
                --disable-shared --enable-static \
                CPPFLAGS="-I$SYSROOT/usr/include" \
                --prefix="$BROOT/libXau-inst" >"$BROOT/libXau-configure.log" 2>&1
    make -j"$(nproc)" >"$BROOT/libXau-make.log" 2>&1
    make install >>"$BROOT/libXau-make.log" 2>&1
  )
  cp "$BROOT/libXau-inst/lib/libXau.a" "$SYSROOT/usr/lib/libXau.a"
  cp -r "$BROOT/libXau-inst/include/." "$SYSROOT/usr/include/" 2>/dev/null || true
  echo "[x11] built libXau.a ($(stat -c%s "$SYSROOT/usr/lib/libXau.a") bytes)"
fi

for lib in libX11 libXext libxcb libXau libXdmcp; do
  [[ -f "$SYSROOT/usr/lib/$lib.a" ]] || { echo "[x11] ERROR: $lib.a missing" >&2; exit 1; }
done

cat >"$ENVFILE" <<EOF
# generated by tools/linux-doom/build-x11-musl-sysroot.sh
X11_MUSL_SYSROOT="$SYSROOT"
X11_MUSL_CFLAGS="-I$SYSROOT/usr/include"
# Static link order matters: Xext -> X11 -> xcb -> Xau/Xdmcp -> libc.
X11_MUSL_LIBS="-L$SYSROOT/usr/lib -lXext -lX11 -lxcb -lXau -lXdmcp"
EOF
echo "[x11] sysroot ready: $SYSROOT"
echo "[x11] env:           $ENVFILE"
