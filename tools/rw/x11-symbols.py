#!/usr/bin/env python3
"""tools/rw/x11-symbols.py — the exact X11 surface RimWorld binds.

Two independent sources, merged because Unity reaches Xlib both ways:

  dlsym  — SDL inside UnityPlayer.so has *no* undefined X symbols (measured:
           `nm -D --undefined-only UnityPlayer.so | grep -c ' X'` = 0); it
           dlopens libX11.so.6 and friends and resolves every entry point by
           name.  `ltrace -F ltrace.conf -e dlopen+dlsym` records those names.
  link   — libGLX_mesa.so.0 / libXcursor.so.1 / libXfixes.so.3 … bind Xlib
           symbols at load time; `LD_DEBUG=bindings` records those.

Each name is attributed to the system DSO that exports it, so an implementer
knows which compat DSO must provide it (frozen interface F4).

Usage: x11-symbols.py <ltrace-dlsym-log> <ld-debug-bindings-log>
"""
import re
import subprocess
import sys
from collections import Counter, defaultdict
from datetime import date

# Libraries SDL dlopens, plus the ones Mesa's GLX pulls in.  Order matters only
# for attribution when two libs export the same name (libX11 wins).
XLIBS = [
    "libX11.so.6", "libXext.so.6", "libXfixes.so.3", "libXrender.so.1",
    "libXrandr.so.2", "libXi.so.6", "libXinerama.so.1", "libXcursor.so.1",
    "libXss.so.1", "libXxf86vm.so.1", "libXshape.so.0",
]
SEARCH = ["/usr/lib/x86_64-linux-gnu", "/lib/x86_64-linux-gnu", "/usr/lib64"]

DLSYM = re.compile(r'dlsym\([^,]+, "([^"]+)"\)')
BIND = re.compile(
    r"binding file (?P<src>\S+) \[\d+\] to (?P<dst>\S+) \[\d+\]:\s+"
    r"normal symbol [`'\"](?P<sym>[^'\"`]+)['\"]"
)


def exports(lib):
    for d in SEARCH:
        try:
            out = subprocess.run(
                ["nm", "-D", "--defined-only", f"{d}/{lib}"],
                capture_output=True, text=True, timeout=30)
        except (OSError, subprocess.SubprocessError):
            continue
        if out.returncode == 0:
            syms = set()
            for line in out.stdout.splitlines():
                parts = line.split()
                if len(parts) >= 3 and parts[1] in "TDBRWVi":
                    syms.add(parts[2].split("@")[0])
            return syms
    return set()


def main():
    if len(sys.argv) < 3:
        print(__doc__, file=sys.stderr)
        return 2
    dlsym_log, bind_log = sys.argv[1], sys.argv[2]

    owners = {}
    for lib in XLIBS:
        for s in exports(lib):
            owners.setdefault(s, lib)

    via = defaultdict(set)
    with open(dlsym_log, "r", errors="replace") as f:
        for line in f:
            m = DLSYM.search(line)
            if m and m.group(1).startswith("X"):
                via[m.group(1)].add("dlsym")

    bind_src = Counter()
    with open(bind_log, "r", errors="replace") as f:
        for line in f:
            m = BIND.search(line)
            if not m:
                continue
            dst = m.group("dst").rsplit("/", 1)[-1]
            if not dst.startswith("libX"):
                continue
            via[m.group("sym")].add("link")
            bind_src[dst] += 1

    known = {s: v for s, v in via.items() if s in owners}
    unknown = sorted(s for s in via if s not in owners)
    per_lib = Counter(owners[s] for s in known)
    n_dlsym = sum(1 for v in known.values() if "dlsym" in v)
    n_link = sum(1 for v in known.values() if "link" in v)

    print("# X11 symbols RimWorld binds — generated by tools/rw/x11-symbols.py")
    print(f"# sources: {dlsym_log} , {bind_log}")
    print(f"# date: {date.today().isoformat()}")
    print(f"# distinct symbols: {len(known)} | via dlsym: {n_dlsym} | via link-time binding: {n_link}")
    print("# per compat DSO (F4 must export these): " +
          ", ".join(f"{k}={v}" for k, v in sorted(per_lib.items())))
    print(f"# unresolved-by-system-Xlib names (dropped, {len(unknown)}): " +
          ", ".join(unknown[:12]) + (" …" if len(unknown) > 12 else ""))
    print(f"# link-time binding events into libX*: {sum(bind_src.values())} "
          f"({', '.join(f'{k}={v}' for k, v in sorted(bind_src.items()))})")
    print("# columns: symbol <TAB> owning system DSO <TAB> how the game reaches it")
    for sym in sorted(known):
        print(f"{sym}\t{owners[sym]}\t{'+'.join(sorted(known[sym]))}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
