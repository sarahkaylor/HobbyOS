#!/usr/bin/env bash
# tools/rw/run-guest-sha.sh — build the in-guest SHA-256/maps probe and run it
# as a desktop app, so every file under /RWMANAGED is hashed by the *guest's*
# VFS (the path Mono's mmaps are served from), not by mtools on the host.
#
# Output (serial): [SHA] <name> <sha256> <bytes> per file, [MMAP]/[SEEK]/[COW]
# for the assemblies, then [MAPS] <one row per region>.  Compare the [SHA] rows
# with `sha256sum $RW_EXPORT/RimWorldLinux_Data/Managed/*`.
#
# The probe is a native .BIN launched from the Apps menu (root scan), so the
# disk image must already carry the desktop staging.  This script stages the
# app and then re-runs the desktop harness with RW_SKIP_BUILD=1 (no rebuild,
# no unit tier in this worktree while it runs).
set -uo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
# shellcheck source=tools/rw/lane.sh
. "$ROOT/tools/rw/lane.sh"
cd "$ROOT" || exit 2
OUT="$ROOT/obj/rw-desktop"
IMG="$ROOT/disk.img"
HOST="$RW_EXPORT/RimWorldLinux_Data/Managed"
[ -d "$HOST" ] || { echo "no Managed tree at $HOST"; exit 2; }
[ -f "$IMG" ] || { echo "no disk.img — run tools/rw/run-rimworld-desktop.sh once"; exit 2; }

python3 - "$HOST" "$ROOT/obj/rwsha_files.h" <<'PY'
import os, sys
host, out = sys.argv[1], sys.argv[2]
names = sorted(n for n in os.listdir(host) if os.path.isfile(os.path.join(host, n)))
with open(out, "w") as f:
    f.write("/* generated by tools/rw/run-guest-sha.sh */\n")
    f.write("struct rwfile { const char *name; unsigned long size; };\n")
    f.write("static const struct rwfile RW_FILES[] = {\n")
    for n in names:
        f.write('  { "%s", %dUL },\n' % (n, os.path.getsize(os.path.join(host, n))))
    f.write("};\n#define RW_NFILES %d\n" % len(names))
print("files:", len(names))
PY

RESINC="$(clang -print-resource-dir)/include"
clang -O2 -Wall -Wextra -g -Isrc/user_include -Isrc/user_include/graphics \
      -Isrc/include -Isrc/libc/include -Iobj --target=x86_64-none-elf \
      -ffreestanding -mno-red-zone -nostdinc -isystem "$RESINC" \
      -mcmodel=large -DRWSHA_GUEST -c src/user/rwsha.c -o obj/rwsha.o || exit 2
ld.lld -T src/user/linker.ld -e _start -o obj/rwsha.elf obj/rwsha.o obj/intel/libc.a || exit 2
llvm-objcopy -O binary obj/rwsha.elf obj/rwsha.bin || exit 2
mmd -i "$IMG" ::/GAMES >/dev/null 2>&1 || true
mcopy -o -i "$IMG" obj/rwsha.bin ::/GAMES/SHA256.BIN || exit 2
echo "staged ::/GAMES/SHA256.BIN ($(stat -c %s obj/rwsha.bin) bytes)"

echo "== run (RW_SKIP_BUILD=1, app SHA256.BIN)"
RW_SKIP_BUILD=1 RW_APP=SHA256.BIN bash tools/rw/run-rimworld-desktop.sh \
    --timeout 420 --run-timeout 120 >"$OUT/sha-run.out" 2>&1
S="$OUT/serial-desktop.log"
echo "--- rows ---"
grep -aE "\[SHA\]|\[MMAP\]|\[SEEK\]|\[COW\]|\[MAPS\]" "$S" | head -140
echo "--- compare against the host ---"
python3 - "$S" "$HOST" <<'PY'
import re, os, sys, hashlib
log, host = sys.argv[1], sys.argv[2]
text = open(log, errors="ignore").read()
rows = dict(re.findall(r"\[SHA\] (\S+) ([0-9a-f]{64})", text))
bad = [n for n in sorted(os.listdir(host))
       if os.path.isfile(os.path.join(host, n)) and
       rows.get(n) != hashlib.sha256(open(os.path.join(host, n), "rb").read()).hexdigest()]
print(f"guest rows={len(rows)} mismatches={len(bad)}")
for n in bad[:10]:
    print("  DIFF", n)
PY
