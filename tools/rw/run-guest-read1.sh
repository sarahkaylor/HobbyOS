#!/usr/bin/env bash
# tools/rw/run-guest-read1.sh — L34: one-shot read audit, end to end.
#
# Builds src/user/rwread1.c with a generated table of the game's real asset
# files (path, size, host SHA-256), stages it as /GAMES/READ1.BIN, boots the
# desktop and runs it.  Each file is read with ONE read(fd, buf, size) and the
# returned count + digest are compared with the host's bytes.
#
# A short count on a regular file below EOF is a kernel bug; so is a correct
# count with a wrong digest.  Either would make Unity reject a scene file.
#
# Output: [R1] rows in obj/rw-desktop/serial-desktop.log, plus the summary in
# obj/rw-desktop/read1.out.
set -uo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
# shellcheck source=tools/rw/lane.sh
. "$ROOT/tools/rw/lane.sh"
cd "$ROOT" || exit 2
export HOME=/home/sarah
OUT="$ROOT/obj/rw-desktop"
IMG="$ROOT/disk.img"
GAME="$RW_EXPORT"
[ -d "$GAME/RimWorldLinux_Data" ] || { echo "no game tree at $GAME"; exit 2; }
[ -f "$IMG" ] || { echo "no disk.img — run tools/rw/run-rimworld-desktop.sh once"; exit 2; }

python3 - "$GAME" "$ROOT/obj/rwread_files.h" <<'PY'
import hashlib, os, sys
game, out = sys.argv[1]
data = os.path.join(game, "RimWorldLinux_Data")
rel = [
    ("globalgamemanagers",                  "/NFS/RimWorldLinux_Data/"),
    ("globalgamemanagers.assets",           "/NFS/RimWorldLinux_Data/"),
    ("globalgamemanagers.assets.resS",      "/NFS/RimWorldLinux_Data/"),
    ("level0",                              "/NFS/RimWorldLinux_Data/"),
    ("level1",                              "/NFS/RimWorldLinux_Data/"),
    ("resources.assets",                    "/NFS/RimWorldLinux_Data/"),
    ("sharedassets0.assets",                "/NFS/RimWorldLinux_Data/"),
    ("sharedassets1.assets",                "/NFS/RimWorldLinux_Data/"),
]
rows = []
for name, pre in rel:
    p = os.path.join(data, name)
    if not os.path.isfile(p):
        continue
    h = hashlib.sha256(open(p, "rb").read()).hexdigest()
    rows.append((name, pre + name, os.path.getsize(p), h))
# The bind path and the biggest DSO: /RWMANAGED is a vfs_bind prefix, and the
# DSOs are FAT16 file objects — both are read paths the assets never touch.
extra = [
    ("mscorlib.dll", "/RWMANAGED/", os.path.join(data, "Managed/mscorlib.dll")),
    ("UnityPlayer.so", "/RWDSO/", os.path.join(game, "UnityPlayer.so")),
]
for name, pre, p in extra:
    if os.path.isfile(p):
        h = hashlib.sha256(open(p, "rb").read()).hexdigest()
        rows.append((name, pre + name, os.path.getsize(p), h))
with open(out, "w") as f:
    f.write("/* generated by tools/rw/run-guest-read1.sh */\n")
    f.write("struct rw_read_file { const char *name; const char *path;\n")
    f.write("                      unsigned long size; const char *sha; };\n")
    f.write("static const struct rw_read_file RW_READ_FILES[] = {\n")
    for n, p, s, h in rows:
        f.write('  { "%s", "%s", %dUL, "%s" },\n' % (n, p, s, h))
    f.write("};\n#define RW_NREADS %d\n" % len(rows))
print("files:", len(rows), "bytes:", sum(r[2] for r in rows))
PY

RESINC="$(clang -print-resource-dir)/include"
clang -O2 -Wall -Wextra -g -Isrc/user_include -Isrc/user_include/graphics \
      -Isrc/include -Isrc/libc/include -Iobj --target=x86_64-none-elf \
      -ffreestanding -mno-red-zone -nostdinc -isystem "$RESINC" \
      -mcmodel=large -c src/user/rwread1.c -o obj/rwread1.o || exit 2
ld.lld -T src/user/linker.ld -e _start -o obj/rwread1.elf obj/rwread1.o obj/intel/libc.a || exit 2
llvm-objcopy -O binary obj/rwread1.elf obj/rwread1.bin || exit 2
mmd -i "$IMG" ::/GAMES >/dev/null 2>&1 || true
mcopy -o -i "$IMG" obj/rwread1.bin ::/GAMES/READ1.BIN || exit 2
echo "staged ::/GAMES/READ1.BIN ($(stat -c %s obj/rwread1.bin) bytes)"

echo "== run (RW_SKIP_BUILD=1, app READ1.BIN)"
RW_SKIP_BUILD=1 RW_APP=READ1.BIN bash tools/rw/run-rimworld-desktop.sh \
    --timeout 420 --run-timeout 300 >"$OUT/read1-run.out" 2>&1
S="$OUT/serial-desktop.log"
{
  echo "--- [R1] rows ---"
  grep -aE "\[R1\]" "$S"
  echo "--- verdict ---"
  python3 - "$S" <<'PY'
import re, sys
t = open(sys.argv[1], errors="ignore").read()
rows = re.findall(r"\[R1\] (\S+) want=(\d+) fstat=(-?\d+) seekend=(-?\d+) got=(-?\d+) sha=([0-9a-f]{64}) (count=\S+) (sha=\S+)", t)
if not rows:
    print("NO [R1] ROWS — probe did not run")
else:
    bad = [r for r in rows if r[6] != "count=OK" or r[7] != "sha=OK"]
    print(f"files={len(rows)} short_or_diff={len(bad)}")
    for r in bad:
        print("  BAD", r[0], "want", r[1], "got", r[4], r[6], r[7])
    for r in rows:
        print(f"  {r[0]:32s} want={r[1]:>9s} got={r[4]:>9s} {r[6]} {r[7]}")
PY
} | tee "$OUT/read1.out"
